#!/usr/bin/env node
/* Embed js/data/sources.verified.json as js/data/sources.data.js, so the sources load without a
   server (the page also works when opened straight from disk). Run after editing the JSON. */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'js/data/sources.verified.json'), 'utf8'));
const out = path.join(root, 'js/data/sources.data.js');
fs.writeFileSync(out, `/* Generated by tools/build-sources.js from sources.verified.json. Do not edit by hand. */\nwindow.SOURCES && (SOURCES.data = ${JSON.stringify(data, null, 1)});\n`);
console.log(`wrote ${out}: ${Object.values(data).reduce((n, v) => n + v.length, 0)} claims across ${Object.keys(data).length} stations`);
