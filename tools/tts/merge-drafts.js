#!/usr/bin/env node
/* Collect audio/narration/drafts/<id>.json ({ en, ar }) into js/data/narration.extra.js, which
   js/core/narration.js merges into its script. Drafts override built-in entries with the same id. */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..'), dir = path.join(root, 'audio/narration/drafts');
const out = {};
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort() : []) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  if (d.en && d.ar) out[f.replace(/\.json$/, '')] = { en: d.en, ar: d.ar };
}
fs.writeFileSync(path.join(root, 'js/data/narration.extra.js'), `/* Generated by tools/tts/merge-drafts.js. Do not edit by hand. */\nwindow.NARRATION_EXTRA = ${JSON.stringify(out, null, 1)};\n`);
console.log(`merged ${Object.keys(out).length} narration drafts: ${Object.keys(out).join(', ')}`);
